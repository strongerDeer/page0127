import { describe, expect, it } from 'vitest';

import { weekOf } from './weekOf';

describe('weekOf', () => {
  it('목요일이면 그 주 월~일', () => {
    expect(weekOf('2026-11-26')).toEqual([
      '2026-11-23',
      '2026-11-24',
      '2026-11-25',
      '2026-11-26',
      '2026-11-27',
      '2026-11-28',
      '2026-11-29',
    ]);
  });

  it('일요일은 앞 주 월요일부터(주의 마지막 날)', () => {
    expect(weekOf('2026-11-29')[0]).toBe('2026-11-23');
    expect(weekOf('2026-11-29')[6]).toBe('2026-11-29');
  });

  it('달·해가 바뀌는 주도 이어진다', () => {
    expect(weekOf('2026-12-31')).toEqual([
      '2026-12-28',
      '2026-12-29',
      '2026-12-30',
      '2026-12-31',
      '2027-01-01',
      '2027-01-02',
      '2027-01-03',
    ]);
  });
});

/**
 * 응원 카드 첫 줄 — 올해 끝까지 읽은 책 수에 따라 다섯 갈래(HJ 2026-11-27 설계 페이지).
 *
 * 평가하는 말(많이·적게·대단해요)은 쓰지 않는다. 숫자를 있는 그대로 말하고 한 해를 다독인다.
 * 독서량은 "끝까지 읽은 책"으로 부른다(브랜드 목소리 점검 2026-11-26).
 */
export const toCheerLine = (books: number): string => {
  const n = Math.max(0, Math.floor(books));
  if (n === 0) return '책을 펼 틈도 없이 바빴던 한 해, 수고 많았어요.';
  if (n <= 5)
    return `끝까지 읽은 책 ${n}권과 함께, 천천히 꾸준히 걸어온 한 해였어요.`;
  if (n <= 20)
    return `끝까지 읽은 책 ${n}권, 계절마다 책을 곁에 두고 지낸 한 해였어요.`;
  if (n <= 50) return `끝까지 읽은 책 ${n}권, 책장이 부쩍 자란 한 해였어요.`;
  return `끝까지 읽은 책 ${n}권, 책장이 한 칸 더 필요해진 한 해였어요.`;
};
